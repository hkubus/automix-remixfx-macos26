// RemixFXEnabler — makes Apple's AURemixFX (aufx/remx/appl) available inside Music on macOS 26 (x86_64),
// then unlocks AutoMix and redirects the transition catalog/graph so the engine can build RemixFX transitions.
//
// RemixFX ships only in macOS 27's SonicAudioUnits.framework, which is absent on 26. We transplant Apple's
// own native x86_64 build of it: the slide-applied image (payload/SonicAudioUnits) plus a fixup sidecar
// (payload/SonicAudioUnits.fixups) are mapped in-process by sau_load() [sauload.c], which reconstructs the
// rebases / data binds / shared-GOT imports that the cache strips, then calls registerSonicAudioUnits().
//
// It also *drives* RemixFX during transitions (rxdrive.c, "Path A"): every aufx/remx instance's dispatch is
// wrapped; the RemixFX styles generated by make_catalog.py carry a progress/tempo carrier into pseudo-params
// of the AURemixFX node, and rxdrive replays macOS 27's REMIX_FX envelopes (RemixFXStyles.json) onto the AU.
//
// It also makes 26's beat-matched planner plan the way macOS 27 does (planner27.c): with make_catalog.py's
// default catalog (styles 17-20 at their real IDs) 26 evaluates 27's Dance/Hip-Hop/Pop styles next to its own
// 8/9/12, with 27's genre gates, base scores and factor lists, and picks with 27's seeded weighted-random rule.
// REMIXFX_PLANNER27=0 disables it; 1 (default) logs each decision, 2 adds inputs, 3 every candidate score.
// The default catalog needs it: with it off, 26 only evaluates 8/9/12 and never plays RemixFX (use --slots).
//
// Loaded into Music via DYLD_INSERT_LIBRARIES (AMFI must be permissive, as it already is on this box).
// Acts only inside com.apple.Music. Nothing here touches the sealed system volume.
// Env: REMIXFX_TRACE=<path> (default /tmp/remixfx-trace.log, "off" to disable), REMIXFX_VERBOSE=0|1|2 (default 1),
//      REMIXFX_PLANNER27=0|1|2|3 (default 1).

