static os_log_t gLog;
static NSString *gBase;   // ~/Library/Application Support/RemixFX
static NSString *gResDir; // .../Resources

static void Override(Class cls, SEL sel, BOOL isClassMethod, id block) {
    if (!cls) { os_log_error(gLog, "class missing for %{public}s", sel_getName(sel)); return; }
    Method m = isClassMethod ? class_getClassMethod(cls, sel) : class_getInstanceMethod(cls, sel);
    if (!m) { os_log_error(gLog, "method missing %{public}s", sel_getName(sel)); return; }
    method_setImplementation(m, imp_implementationWithBlock(block));
    os_log(gLog, "patched %{public}c[%{public}s %{public}s]", isClassMethod?'+':'-', class_getName(cls), sel_getName(sel));
}

// ---- transition catalog / DSP graph redirection (serve our 27-derived copies) ----
static NSString *RedirectPath(NSString *name, NSString *ext) {
    if (!name) return nil;
    NSString *base = name, *e = ext;
    if (!e.length && name.pathExtension.length) { base = name.stringByDeletingPathExtension; e = name.pathExtension; }
    if (!(([base isEqualToString:@"TransitionStyles"] && [e isEqualToString:@"json"]) ||
          ([base isEqualToString:@"DSPGraph"] && [e isEqualToString:@"dspg"]))) return nil;
    NSString *p = [gResDir stringByAppendingPathComponent:[base stringByAppendingPathExtension:e]];
    return [NSFileManager.defaultManager fileExistsAtPath:p] ? p : nil;
}
static IMP oURLExt, oURLExtSub, oPathType, oPathTypeDir;
static NSURL *H_URLExt(NSBundle *s, SEL c, NSString *n, NSString *e){ NSString*p=RedirectPath(n,e); if(p){os_log(gLog,"redirect %{public}@.%{public}@ -> %{public}@",n,e,p);return [NSURL fileURLWithPath:p];} return ((NSURL*(*)(id,SEL,id,id))oURLExt)(s,c,n,e); }
static NSURL *H_URLExtSub(NSBundle *s, SEL c, NSString *n, NSString *e, NSString *d){ NSString*p=RedirectPath(n,e); if(p)return [NSURL fileURLWithPath:p]; return ((NSURL*(*)(id,SEL,id,id,id))oURLExtSub)(s,c,n,e,d); }
static NSString *H_PathType(NSBundle *s, SEL c, NSString *n, NSString *e){ NSString*p=RedirectPath(n,e); if(p)return p; return ((NSString*(*)(id,SEL,id,id))oPathType)(s,c,n,e); }
static NSString *H_PathTypeDir(NSBundle *s, SEL c, NSString *n, NSString *e, NSString *d){ NSString*p=RedirectPath(n,e); if(p)return p; return ((NSString*(*)(id,SEL,id,id,id))oPathTypeDir)(s,c,n,e,d); }
static void Hook(SEL sel, IMP repl, IMP *orig){ Method m=class_getInstanceMethod(NSBundle.class,sel); if(!m){os_log_error(gLog,"NSBundle %{public}s missing",sel_getName(sel));return;} *orig=method_setImplementation(m,repl); }

// ---- macOS 27 planner rules (planner27.c) ----
static void SetupPlanner27(void) {
    const char *e = getenv("REMIXFX_PLANNER27");
    if (e && !strcmp(e, "0")) { rx_log("planner27 disabled (REMIXFX_PLANNER27=0)"); return; }
    // Which 27 styles the served catalog has. Option (b) (make_catalog.py default): 15-20 at their real IDs, which
    // 26's BMFCF then evaluates next to 8/9/12. Option (a) (--slots): slots 8/9/12 named "... [27:NN]".
    NSData *d = [NSData dataWithContentsOfFile:[gResDir stringByAppendingPathComponent:@"TransitionStyles.json"]];
    id cat = d ? [NSJSONSerialization JSONObjectWithData:d options:0 error:nil] : nil;
    if ([cat isKindOfClass:NSArray.class])
        for (NSDictionary *s in cat) {
            if (![s isKindOfClass:NSDictionary.class] || ![s[@"id"] isKindOfClass:NSNumber.class]) continue;
            int sid = (int)[s[@"id"] integerValue];
            if (sid >= 15 && sid <= 20) p27_add_style(sid);
            if (![s[@"name"] isKindOfClass:NSString.class]) continue;
            NSString *name = s[@"name"];
            NSRange r = [name rangeOfString:@"[27:"];
            if (r.location != NSNotFound && sid <= 12)
                p27_set_slot_style(sid, [name substringFromIndex:r.location + r.length].intValue);
        }
    int n = p27_install(e && *e ? atoi(e) : 1);
    os_log(gLog, "planner27: %{public}s (%d)", n > 0 ? "27 selection rules active" : "not installed", n);
}

// ---- transplant RemixFX ----
static void LoadRemixFX(void) {
    // Preferred: ~/Library/Audio/Plug-Ins/Components/RemixFX.component serves aufx/remx/appl to every process,
    // including AUHostingServiceXPC where AudioQueue runs the transition DSPGraph. Only fall back to an
    // in-process registration (which that out-of-process graph cannot see) when the bundle isn't installed.
    AudioComponentDescription want = { kAudioUnitType_Effect, 'remx', kAudioUnitManufacturer_Apple, 0, 0 };
    if (AudioComponentFindNext(NULL, &want) && !getenv("REMIXFX_INPROCESS")) {
        fprintf(stderr, "[RemixFX] aufx/remx/appl served by RemixFX.component (no in-process copy)\n");
        os_log(gLog, "aufx/remx/appl served by RemixFX.component");
        rx_log("aufx/remx/appl already registered (RemixFX.component) - skipping in-process transplant");
        return;
    }
    NSString *bin = [gBase stringByAppendingPathComponent:@"SonicAudioUnits"];
    NSString *fx  = [gBase stringByAppendingPathComponent:@"SonicAudioUnits.fixups"];
    if (![NSFileManager.defaultManager fileExistsAtPath:bin] || ![NSFileManager.defaultManager fileExistsAtPath:fx]) {
        os_log_error(gLog, "RemixFX payload missing under %{public}@ — aufx/remx/appl unavailable", gBase); return;
    }
    NSString *env = [gResDir stringByAppendingPathComponent:@"RemixFXStyles.json"];
    int nenv = rx_load_envelopes(env);
    os_log(gLog, "RemixFX envelopes: %d from %{public}@", nenv, env);
    rx_env_dump();
    sau_set_bind_hook(rx_bind_hook);           // wrap aufx/remx/appl's factory so the engine can drive it
    void (*reg)(void) = (void(*)(void)) sau_load(bin.fileSystemRepresentation, fx.fileSystemRepresentation);
    if (!reg) { os_log_error(gLog, "sau_load failed"); return; }
    reg();
    AudioComponentDescription d = { kAudioUnitType_Effect, 'remx', kAudioUnitManufacturer_Apple, 0, 0 };
    AudioComponent c = AudioComponentFindNext(NULL, &d);
    CFStringRef nm=NULL; if(c) AudioComponentCopyName(c,&nm);
    fprintf(stderr, "[RemixFX] aufx/remx/appl %s%s%s\n", c?"AVAILABLE":"NOT FOUND",
            nm?" : ":"", nm?[(__bridge NSString*)nm UTF8String]:"");
    os_log(gLog, "RemixFX registered; aufx/remx/appl %{public}s", c ? "AVAILABLE" : "NOT FOUND");
}

__attribute__((constructor))
static void Init(void) {
    if (![NSBundle.mainBundle.bundleIdentifier isEqualToString:@"com.apple.Music"]) return;
    gLog = os_log_create("dev.remixfx", "init");
    gBase = [NSHomeDirectory() stringByAppendingPathComponent:@"Library/Application Support/RemixFX"];
    gResDir = [gBase stringByAppendingPathComponent:@"Resources"];
    const char *tp = getenv("REMIXFX_TRACE"), *vb = getenv("REMIXFX_VERBOSE");
    if (!tp || strcmp(tp, "off")) rx_trace_open(tp && *tp ? tp : "/tmp/remixfx-trace.log", vb ? atoi(vb) : 1);
    rx_log("RemixFXEnabler in Music pid %d", getpid());

    // AutoMix unlock (same overrides as the basic enabler)
    Class engine = NSClassFromString(@"MPCPlaybackEngine");
    Override(engine, @selector(deviceSupportsSmartTransitions), YES, ^BOOL(id s){ return YES; });
    Override(engine, @selector(deviceSupportsTransitions), YES, ^BOOL(id s){ return YES; });
    Override(NSClassFromString(@"MusicPlaybackPrefsModel"), @selector(hasAlchemy), NO, ^BOOL(id s){ return YES; });
    Class queue = NSClassFromString(@"ITPlayQueueModel");
    Override(queue, @selector(mixingAvailable), NO, ^BOOL(id s){ return YES; });
    Override(queue, @selector(mixingEnabled), NO, ^BOOL(id s){
        id player = ((id(*)(id,SEL))objc_msgSend)(s, @selector(player));
        id st = ((id(*)(id,SEL))objc_msgSend)(player, @selector(playerControlsState));
        return st ? ((BOOL(*)(id,SEL))objc_msgSend)(st, @selector(isTransitionsSupported)) : NO;
    });

    // catalog / graph redirection + RemixFX transplant
    Hook(@selector(URLForResource:withExtension:), (IMP)H_URLExt, &oURLExt);
    Hook(@selector(URLForResource:withExtension:subdirectory:), (IMP)H_URLExtSub, &oURLExtSub);
    Hook(@selector(pathForResource:ofType:), (IMP)H_PathType, &oPathType);
    Hook(@selector(pathForResource:ofType:inDirectory:), (IMP)H_PathTypeDir, &oPathTypeDir);
    LoadRemixFX();
    SetupPlanner27();
    os_log(gLog, "RemixFXEnabler loaded (base %{public}@)", gBase);
}
